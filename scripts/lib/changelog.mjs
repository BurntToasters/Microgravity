import { fail } from "./core.mjs";

const changelogTitle = "# Microgravity changelog\n\n";

export function changelogSection(version, contents) {
  const heading = new RegExp(`^## ${version.replaceAll(".", "\\.")}(?:\\s|$)`, "m");
  const match = heading.exec(contents);
  if (!match) fail(`CHANGELOG.md has no ${version} release section.`);
  const start = match.index;
  const next = contents.slice(start + match[0].length).search(/^## \S/m);
  const end = next < 0 ? undefined : start + match[0].length + next;
  return contents.slice(start, end).trim();
}

const repositoryUrl = "https://github.com/BurntToasters/Microgravity";
const macIcon = "https://github.com/user-attachments/assets/42d7e887-4616-4e8c-b1d3-e44e01340f8c";
export const gpgFingerprint = "F01DAAD63F4688AB0BBEC7085E7752731C2EC359";

// The download and verification header placed above the changelog section in each GitHub release.
export function releaseHeader(info) {
  const download = (name) => `${repositoryUrl}/releases/download/${info.tag}/${name}`;
  const zip = `Microgravity-${info.version}.zip`;
  return [
    ...(info.channel === "beta" ? ["> [!NOTE]", "> 🅱️ This is a Beta build.", ""] : []),
    "# ⬇️ Downloads",
    "",
    `| <img height="20" src="${macIcon}" /> macOS |`,
    "| :-- |",
    `| **ZIP: [universal](${download(zip)})** |`,
    `| **Checksums: [SHA256SUMS](${download("SHA256SUMS")}) / [GPG signature](${download("SHA256SUMS.asc")})** |`,
    "",
    "> Requires macOS 14 or later. The universal build runs natively on Apple silicon and Intel Macs.",
    "",
    "> [!IMPORTANT]",
    "> Microgravity is signed with my Apple Developer ID and notarized by Apple.",
    "> The `.asc` files are detached GPG signatures. Verify them with the Microgravity release key,",
    `> fingerprint \`${gpgFingerprint}\`.`,
    "> In-app updates are delivered by Sparkle and verified with an EdDSA signature before they install.",
    "",
    "### ℹ️ Enjoying Microgravity? Consider [❤️ Supporting Me! ❤️](https://rosie.run/support)",
    "",
  ].join("\n");
}

export function releaseNotes(info, contents) {
  const section = changelogSection(info.version, contents).replace(/^## \S+[^\n]*/, `## Changes in \`${info.tag}:\``);
  return `${releaseHeader(info)}\n${section}\n\nSource: ${info.tag} at ${info.version}. See the tagged repository for the complete corresponding source and bundled notices.\n`;
}

// Text that sync-version and early drafts write in place of real notes. A release section containing it is not publishable.
export const placeholderReleaseNotes = ["Initial public release foundation.", "Release notes pending."];

// Returns human-readable problems with a release section: missing section, placeholder text, or fewer
// bullet items than `minimumItems`. An empty array means the section is publishable.
export function releaseNotesFailures(version, contents, { minimumItems = 1 } = {}) {
  let section;
  try {
    section = changelogSection(version, contents);
  } catch (error) {
    return [error.message];
  }
  const failures = [];
  for (const placeholder of placeholderReleaseNotes) {
    if (section.includes(placeholder)) failures.push(`CHANGELOG.md ${version} still contains placeholder text: "${placeholder}"`);
  }
  const items = section.split("\n").filter((line) => /^- \S/.test(line)).length;
  if (items < minimumItems) failures.push(`CHANGELOG.md ${version} has ${items} bullet item(s); at least ${minimumItems} are required`);
  return failures;
}

const downloadsStart = "<!-- downloads:start (generated by npm run sync-version; do not edit) -->";
const downloadsEnd = "<!-- downloads:end -->";

// The changelog starts with the title, then the downloads block for the current version, then the release sections.
// sync-version rewrites the block whenever the version changes and adds a placeholder section for a new version.
export function expectedChangelog(current, version) {
  if (!current.startsWith(changelogTitle)) fail(`CHANGELOG.md must start with "${changelogTitle.trim()}".`);
  let rest = current.slice(changelogTitle.length);
  const blockStart = rest.indexOf(downloadsStart);
  if (blockStart !== -1) {
    if (rest.slice(0, blockStart).trim()) fail("CHANGELOG.md must have nothing between the title and the downloads block.");
    const blockEnd = rest.indexOf(downloadsEnd, blockStart);
    if (blockEnd === -1) fail(`CHANGELOG.md downloads block has no "${downloadsEnd}" marker.`);
    rest = rest.slice(blockEnd + downloadsEnd.length).replace(/^\n+/, "");
  }
  if (!new RegExp(`^## ${version.replaceAll(".", "\\.")}(?:\\s|$)`, "m").test(rest)) rest = `## ${version}\n\nRelease notes pending.\n\n${rest}`;
  const info = { version, tag: `v${version}`, channel: version.includes("-beta.") ? "beta" : "stable" };
  return `${changelogTitle}${downloadsStart}\n${releaseHeader(info)}${downloadsEnd}\n\n${rest}`;
}
